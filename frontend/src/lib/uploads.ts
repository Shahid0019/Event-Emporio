/**
 * Image upload rules shared by the browser uploader and the upload API.
 * Files go straight from the browser to S3 with a short-lived presigned
 * POST; S3 itself enforces the size limit and content type, so the server
 * never handles the bytes. SVG is deliberately not accepted (it can carry
 * scripts).
 */

export const UPLOAD_MAX_BYTES = 8 * 1024 * 1024;

export const UPLOAD_TYPES = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/avif": "avif",
} as const;

export type UploadContentType = keyof typeof UPLOAD_TYPES;

export const UPLOAD_ACCEPT = Object.keys(UPLOAD_TYPES).join(",");

/** Where in the bucket each kind of image lives. */
export const UPLOAD_FOLDERS = ["products", "kit-products", "kit-functions", "categories"] as const;
export type UploadFolder = (typeof UPLOAD_FOLDERS)[number];

export const isUploadType = (type: string): type is UploadContentType => type in UPLOAD_TYPES;

/** Human-readable reason a file can't be uploaded, or null if it's fine. */
export function uploadProblem(file: { type: string; size: number; name?: string }): string | null {
  if (!isUploadType(file.type)) return `${file.name ?? "This file"} isn't a JPG, PNG, WebP or AVIF image.`;
  if (file.size > UPLOAD_MAX_BYTES) return `${file.name ?? "This file"} is over ${UPLOAD_MAX_BYTES / 1024 / 1024} MB.`;
  if (file.size === 0) return `${file.name ?? "This file"} is empty.`;
  return null;
}

/** Object keys are generated by the server only: folder/yyyy/mm/uuid.ext — nothing from the file name. */
export const UPLOAD_KEY_PATTERN = new RegExp(
  `^(${UPLOAD_FOLDERS.join("|")})/\\d{4}/\\d{2}/[0-9a-f-]{36}\\.(${Object.values(UPLOAD_TYPES).join("|")})$`,
);

export function newUploadKey(folder: UploadFolder, type: UploadContentType, now = new Date()): string {
  const month = String(now.getUTCMonth() + 1).padStart(2, "0");
  return `${folder}/${now.getUTCFullYear()}/${month}/${crypto.randomUUID()}.${UPLOAD_TYPES[type]}`;
}

/** S3 settings from the environment (server only), or null when uploads to S3 aren't configured. */
export function s3Settings() {
  const bucket = process.env.S3_BUCKET;
  const region = process.env.AWS_REGION;
  if (!bucket || !region) return null;
  const publicBaseUrl = (process.env.S3_PUBLIC_BASE_URL || `https://${bucket}.s3.${region}.amazonaws.com`).replace(/\/$/, "");
  return { bucket, region, publicBaseUrl };
}
