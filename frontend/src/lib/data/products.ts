type VariantSeed = { options: Record<string, string>; price: number; compareAtPrice?: number; stock: number; imageIndex?: number };

function variants(sku: string, seeds: VariantSeed[]): ProductVariant[] {
  return seeds.map((seed, i) => ({
    id: `${sku}-v${i + 1}`.toLowerCase(),
    sku: `${sku}-${String(i + 1).padStart(2, "0")}`,
    ...seed,
  }));
}

function single(sku: string, price: number, stock: number, compareAtPrice?: number): ProductVariant[] {
  return [{ id: `${sku}-v1`.toLowerCase(), sku, options: {}, price, compareAtPrice, stock }];
}

